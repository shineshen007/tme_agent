"""Install a user-level ``multiomics`` launcher and activate it on PATH.

The launcher is deliberately a thin shim. It prepends the install root to
``PYTHONPATH`` and runs the project's own virtual-environment Python; it never
changes the caller's current directory. ``--project-root`` is placed before any
user arguments so an explicit value still wins (the CLI keeps the last one).

Only per-user locations are touched: ``~/.local/bin``, the user's shell profile
(on POSIX) or the current user's ``Path`` environment value (on Windows). No
administrator rights and no system-wide configuration are required.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import stat
import sys
import uuid
from pathlib import Path

COMMAND = "multiomics"
MARKER = "tme_agent launcher"
BEGIN = "# >>> tme_agent multiomics launcher >>>"
END = "# <<< tme_agent multiomics launcher <<<"
MARKER_FILE = ".runtime/command_link.json"


class LauncherConflict(RuntimeError):
    """A foreign file already occupies the launcher path."""


def _is_windows() -> bool:
    return os.name == "nt"


def _home(home=None) -> Path:
    return Path(home).expanduser() if home is not None else Path.home()


def default_bin_dir(home=None) -> Path:
    value = os.environ.get("MULTIOMICS_BIN_DIR")
    if value:
        return Path(value).expanduser()
    return _home(home) / ".local/bin"


def launcher_path(bin_dir: Path) -> Path:
    name = COMMAND + (".cmd" if _is_windows() else "")
    return Path(bin_dir) / name


def _normalized(value) -> str:
    text = os.path.expandvars(os.path.expanduser(str(value))).strip().strip('"')
    return os.path.normcase(os.path.abspath(text)).rstrip(os.sep) or os.sep


def path_contains(entries, target) -> bool:
    wanted = _normalized(target)
    return any(_normalized(item) == wanted for item in entries if str(item).strip())


def _read_managed(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    return MARKER in text


def _atomic_write(path: Path, text: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + "." + uuid.uuid4().hex + ".tmp")
    fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.chmod(temp, mode)
        os.replace(temp, path)
    finally:
        try:
            if temp.exists():
                temp.unlink()
        except OSError:
            pass


def _posix_launcher(root: Path, python: Path) -> str:
    root_q = shlex.quote(str(root))
    python_q = shlex.quote(str(python))
    return (
        "#!/bin/sh\n"
        f"# {MARKER}\n"
        "# Generated by tme_agent setup. Rerun setup or "
        "`python -m native_dist.command_link install` to refresh.\n"
        "unset MULTIOMICS_APP_ROOT PYTHONHOME PYTHONSTARTUP\n"
        "PYTHONUTF8=1\n"
        "export PYTHONUTF8\n"
        f"PYTHONPATH={root_q}${{PYTHONPATH:+:$PYTHONPATH}}\n"
        "export PYTHONPATH\n"
        f'exec {python_q} -P -m multiomics_tui --project-root {root_q} "$@"\n'
    )


def _batch_path(path: Path) -> str:
    # Percent signs introduce variables when a .cmd file is parsed.
    return str(path).replace("%", "%%")


def _windows_launcher(root: Path, python: Path) -> str:
    root_s = _batch_path(root)
    python_s = _batch_path(python)
    return (
        "@echo off\n"
        f"rem {MARKER}\n"
        "setlocal\n"
        "chcp 65001 >nul\n"
        'set "PYTHONUTF8=1"\n'
        'set "MULTIOMICS_APP_ROOT="\n'
        'set "PYTHONHOME="\n'
        'set "PYTHONSTARTUP="\n'
        f'set "PYTHONPATH={root_s};%PYTHONPATH%"\n'
        f'"{python_s}" -P -m multiomics_tui --project-root "{root_s}" %*\n'
        'set "MULTIOMICS_EXIT=%ERRORLEVEL%"\n'
        "exit /b %MULTIOMICS_EXIT%\n"
    )


def launcher_text(root: Path, python: Path) -> str:
    return _windows_launcher(root, python) if _is_windows() else _posix_launcher(root, python)


def shell_profile(home=None, shell=None):
    """Return ``(profile_path, syntax)`` for the current shell."""
    name = Path(shell or os.environ.get("SHELL", "")).name.lower()
    base = _home(home)
    if name == "fish":
        return base / ".config/fish/config.fish", "fish"
    if name == "zsh":
        return base / ".zshrc", "posix"
    if name == "bash":
        return base / (".bash_profile" if sys.platform == "darwin" else ".bashrc"), "posix"
    if not name and sys.platform == "darwin":
        return base / ".zshrc", "posix"
    return base / ".profile", "posix"


def _managed_block(bin_dir: Path, syntax: str) -> str:
    quoted = shlex.quote(str(bin_dir))
    line = (f"set -gx PATH {quoted} $PATH" if syntax == "fish"
            else f"export PATH={quoted}:$PATH")
    return f"\n{BEGIN}\n{line}\n{END}\n"


def _replace_block(text: str, block: str) -> str:
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        return pattern.sub(block.strip("\n"), text, count=1)
    return (text.rstrip("\n") + "\n" if text.strip() else "") + block.lstrip("\n")


def _ensure_posix_path(bin_dir: Path, home=None, shell=None) -> dict:
    profile, syntax = shell_profile(home, shell)
    target = profile.resolve() if profile.is_symlink() else profile
    try:
        existing = target.read_text(encoding="utf-8") if target.is_file() else ""
    except OSError as exc:
        return {"path_configured": False, "path_changed": False,
                "warning": f"Cannot read {target}: {exc}", "profile": str(target)}
    block = _managed_block(bin_dir, syntax)
    if BEGIN in existing and END in existing:
        updated = _replace_block(existing, block)
        changed = updated != existing
    else:
        updated = existing.rstrip("\n") + ("\n" if existing.strip() else "") + block
        changed = True
    if changed:
        try:
            mode = stat.S_IMODE(target.stat().st_mode) if target.is_file() else 0o644
            _atomic_write(target, updated, mode or 0o644)
        except OSError as exc:
            return {"path_configured": False, "path_changed": False,
                    "warning": f"Cannot write {target}: {exc}", "profile": str(target)}
    return {"path_configured": True, "path_changed": changed,
            "profile": str(target), "restart_required": changed}


def _windows_path_value(bin_dir: Path, value: str) -> str:
    parts = [part for part in value.split(";") if part.strip()]
    if path_contains(parts, bin_dir):
        return value
    return ";".join([*parts, str(bin_dir)])


def _ensure_windows_path(bin_dir: Path) -> dict:
    try:
        import winreg
    except ImportError as exc:  # pragma: no cover - only reachable on Windows
        return {"path_configured": False, "path_changed": False,
                "warning": f"Windows registry access unavailable: {exc}"}
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0,
                            winreg.KEY_READ | winreg.KEY_WRITE) as key:
            try:
                value, kind = winreg.QueryValueEx(key, "Path")
            except FileNotFoundError:
                value, kind = "", winreg.REG_EXPAND_SZ
            updated = _windows_path_value(bin_dir, str(value or ""))
            if updated != value:
                if kind not in (winreg.REG_SZ, winreg.REG_EXPAND_SZ):
                    kind = winreg.REG_EXPAND_SZ
                winreg.SetValueEx(key, "Path", 0, kind, updated)
                _broadcast_environment_change()
                return {"path_configured": True, "path_changed": True,
                        "profile": "HKCU\\Environment", "restart_required": True}
            return {"path_configured": True, "path_changed": False,
                    "profile": "HKCU\\Environment"}
    except OSError as exc:  # pragma: no cover - only reachable on Windows
        return {"path_configured": False, "path_changed": False,
                "warning": f"Cannot update the user Path: {exc}"}


def _broadcast_environment_change() -> None:  # pragma: no cover - Windows only
    try:
        import ctypes
        from ctypes import wintypes
        user32 = ctypes.WinDLL("user32", use_last_error=True)
        send = user32.SendMessageTimeoutW
        send.argtypes = [wintypes.HWND, wintypes.UINT, wintypes.WPARAM,
                         ctypes.c_wchar_p, wintypes.UINT, wintypes.UINT,
                         ctypes.POINTER(ctypes.c_size_t)]
        send.restype = wintypes.LPARAM
        result = ctypes.c_size_t()
        send(0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000, ctypes.byref(result))
    except Exception:
        pass


def ensure_path(bin_dir: Path, home=None, shell=None, environ=None) -> dict:
    environ = os.environ if environ is None else environ
    entries = str(environ.get("PATH", "")).split(os.pathsep)
    if path_contains(entries, bin_dir):
        return {"path_configured": True, "path_changed": False, "profile": "process PATH"}
    return _ensure_windows_path(bin_dir) if _is_windows() else _ensure_posix_path(bin_dir, home, shell)


def remove_path(bin_dir: Path, home=None, *, profile=None) -> dict:
    if _is_windows():
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0,
                                winreg.KEY_READ | winreg.KEY_WRITE) as key:
                try:
                    value, kind = winreg.QueryValueEx(key, "Path")
                except FileNotFoundError:
                    return {"path_changed": False, "profile": "HKCU\\Environment"}
                original = [part for part in str(value or "").split(";") if part.strip()]
                parts = [part for part in original if not path_contains([part], bin_dir)]
                if len(parts) == len(original):
                    return {"path_changed": False, "profile": "HKCU\\Environment"}
                winreg.SetValueEx(key, "Path", 0, kind, ";".join(parts))
                _broadcast_environment_change()
                return {"path_changed": True, "profile": "HKCU\\Environment"}
        except (ImportError, OSError) as exc:  # pragma: no cover - Windows only
            return {"path_changed": False, "warning": str(exc)}
    target = Path(profile) if profile is not None else shell_profile(home)[0]
    target = target.resolve() if target.is_symlink() else target
    try:
        text = target.read_text(encoding="utf-8")
    except OSError:
        return {"path_changed": False, "profile": str(target)}
    pattern = re.compile(r"\n?" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    updated, count = pattern.subn("\n", text)
    if not count:
        return {"path_changed": False, "profile": str(target)}
    try:
        _atomic_write(target, updated.rstrip("\n") + "\n", stat.S_IMODE(target.stat().st_mode) or 0o644)
    except OSError as exc:
        return {"path_changed": False, "warning": str(exc), "profile": str(target)}
    return {"path_changed": True, "profile": str(target), "restart_required": True}


def _marker_path(root: Path) -> Path:
    return Path(root) / MARKER_FILE


def previous_path_preference(root: Path):
    try:
        value = json.loads(_marker_path(root).read_text(encoding="utf-8"))
        return bool(value["path_requested"])
    except (OSError, ValueError, KeyError, TypeError):
        return None


def install(root, *, venv_python=None, bin_dir=None, add_path=True, home=None,
            shell=None, environ=None) -> dict:
    root = Path(root).resolve()
    python = Path(venv_python) if venv_python is not None else root / (
        ".venv/Scripts/python.exe" if _is_windows() else ".venv/bin/python")
    if not python.is_file():
        raise RuntimeError(f"Virtual environment Python is missing: {python}")
    bin_dir = Path(bin_dir) if bin_dir is not None else default_bin_dir(home)
    bin_dir = bin_dir.expanduser().resolve()
    bin_dir.mkdir(parents=True, exist_ok=True)
    path = launcher_path(bin_dir)
    if path.exists():
        if not path.is_file() or not _read_managed(path):
            raise LauncherConflict(f"Refusing to overwrite an existing file: {path}")
    _atomic_write(path, launcher_text(root, python), 0o755 if not _is_windows() else 0o644)
    result = {"launcher": str(path), "bin_dir": str(bin_dir),
              "python": str(python), "path_requested": bool(add_path)}
    if add_path:
        result.update(ensure_path(bin_dir, home=home, shell=shell, environ=environ))
    else:
        result.update({"path_configured": False, "path_changed": False})
    marker = {"schema_version": 1, "launcher": str(path), "bin_dir": str(bin_dir),
              "path_requested": bool(add_path), "profile": result.get("profile")}
    try:
        _atomic_write(_marker_path(root), json.dumps(marker, ensure_ascii=False, indent=2) + "\n", 0o644)
    except OSError as exc:
        result["warning"] = (result.get("warning") + " " if result.get("warning") else "") + \
            f"Cannot record launcher preference: {exc}"
    return result


def status(root=None, *, bin_dir=None, home=None, environ=None) -> dict:
    bin_dir = Path(bin_dir) if bin_dir is not None else default_bin_dir(home)
    bin_dir = bin_dir.expanduser().resolve()
    path = launcher_path(bin_dir)
    environ = os.environ if environ is None else environ
    profile, _ = shell_profile(home)
    if root is not None:
        try:
            marker = json.loads(_marker_path(Path(root)).read_text(encoding="utf-8"))
            if marker.get("profile") and Path(marker["profile"]).is_absolute():
                profile = Path(marker["profile"])
        except (OSError, ValueError, TypeError):
            pass
    result = {
        "launcher": str(path),
        "exists": path.is_file(),
        "managed": _read_managed(path) if path.is_file() else False,
        "bin_dir": str(bin_dir),
        "path_on_current_process": path_contains(
            str(environ.get("PATH", "")).split(os.pathsep), bin_dir),
        "shell_profile": str(profile.resolve() if profile.is_symlink() else profile),
    }
    if result["path_on_current_process"]:
        result["path_configured"] = True
    elif _is_windows():
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
                value, _ = winreg.QueryValueEx(key, "Path")
            result["path_configured"] = path_contains(str(value).split(";"), bin_dir)
        except (ImportError, OSError, FileNotFoundError):
            result["path_configured"] = False
    else:
        try:
            target = profile.resolve() if profile.is_symlink() else profile
            result["path_configured"] = BEGIN in target.read_text(encoding="utf-8")
        except OSError:
            result["path_configured"] = False
    if root is not None:
        result["path_requested"] = previous_path_preference(Path(root))
    return result


def uninstall(*, root=None, bin_dir=None, home=None, environ=None) -> dict:
    bin_dir = Path(bin_dir) if bin_dir is not None else default_bin_dir(home)
    bin_dir = bin_dir.expanduser().resolve()
    path = launcher_path(bin_dir)
    removed = False
    warning = None
    profile = None
    if root is not None:
        try:
            marker = json.loads(_marker_path(Path(root)).read_text(encoding="utf-8"))
            profile = marker.get("profile")
            if not profile or not Path(profile).is_absolute():
                profile = None
        except (OSError, ValueError, TypeError):
            profile = None
    if path.exists():
        if path.is_file() and _read_managed(path):
            path.unlink()
            removed = True
        else:
            warning = f"Left an unmanaged file in place: {path}"
    path_result = remove_path(bin_dir, home=home, profile=profile)
    if root is not None:
        try:
            _marker_path(Path(root)).unlink()
        except OSError:
            pass
    result = {"launcher": str(path), "removed": removed,
              "path_removed": bool(path_result.get("path_changed")),
              "profile": path_result.get("profile")}
    if warning:
        result["warning"] = warning
    if path_result.get("warning"):
        result["warning"] = (result.get("warning") + " " if result.get("warning") else "") + \
            path_result["warning"]
    return result


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Install or inspect the per-user multiomics command")
    sub = parser.add_subparsers(dest="action", required=True)
    for name, help_text in (("install", "Create the launcher and activate PATH"),
                            ("status", "Show launcher and PATH status"),
                            ("uninstall", "Remove the launcher and managed PATH block")):
        item = sub.add_parser(name, help=help_text)
        item.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
        item.add_argument("--bin-dir", type=Path)
        if name == "install":
            item.add_argument("--no-path", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.action == "install":
            result = install(args.project_root, bin_dir=args.bin_dir, add_path=not args.no_path)
        elif args.action == "status":
            result = status(args.project_root, bin_dir=args.bin_dir)
        else:
            result = uninstall(root=args.project_root, bin_dir=args.bin_dir)
    except Exception as exc:  # noqa: BLE001 - CLI surface
        print(f"multiomics command: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
